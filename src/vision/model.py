"""k-NN vision baseline over the deterministic descriptor.

This is deliberately a transparent, CPU-only baseline. A MobileNet/EfficientNet
or ONNX runner can implement ``VisionRunner`` later without changing the API.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
from PIL import Image

from src.vision.features import extract_features


class ArtifactNotFound(RuntimeError):
    pass


@dataclass
class Candidate:
    part_number: str
    label: str
    category: str
    score: float


@dataclass
class VisionBaseline:
    embeddings: np.ndarray
    part_numbers: list[str]
    labels: list[str]
    categories: list[str]
    image_size: int = 64
    name: str = "vision-knn-baseline"
    version: str = "0.1.0"
    runtime: str = "python-numpy"
    precision: str = "fp32"
    metadata: dict = field(default_factory=dict)

    def predict(self, image: Image.Image, k: int = 15, top_k: int = 5) -> list[Candidate]:
        features = extract_features(image, size=self.image_size)
        sims = self.embeddings @ features
        k = min(k, len(sims))
        top_idx = np.argpartition(-sims, k - 1)[:k]
        top_idx = top_idx[np.argsort(-sims[top_idx])]

        scores: dict[str, float] = {}
        for idx in top_idx:
            weight = max(0.0, float(sims[idx]))
            scores[self.part_numbers[idx]] = scores.get(self.part_numbers[idx], 0.0) + weight

        total = sum(scores.values()) or 1.0
        ranked = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)[:top_k]

        lookup = {
            pn: (lab, cat) for pn, lab, cat in zip(self.part_numbers, self.labels, self.categories, strict=False)
        }
        candidates: list[Candidate] = []
        for part_number, raw in ranked:
            label, category = lookup.get(part_number, (part_number, "unknown"))
            candidates.append(
                Candidate(
                    part_number=part_number,
                    label=label,
                    category=category,
                    score=round(min(1.0, raw / total), 4),
                )
            )
        return candidates

    def category_scores(self, image: Image.Image, k: int = 15) -> dict[str, float]:
        candidates = self.predict(image, k=k, top_k=50)
        totals: dict[str, float] = {}
        for c in candidates:
            totals[c.category] = totals.get(c.category, 0.0) + c.score
        return dict(sorted(totals.items(), key=lambda kv: kv[1], reverse=True))

    def save(self, directory: Path) -> Path:
        directory.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(
            directory / "embeddings.npz",
            embeddings=self.embeddings,
            part_numbers=np.array(self.part_numbers),
            labels=np.array(self.labels),
            categories=np.array(self.categories),
        )
        meta = {
            "name": self.name,
            "version": self.version,
            "runtime": self.runtime,
            "precision": self.precision,
            "image_size": self.image_size,
            "train_size": int(self.embeddings.shape[0]),
            "descriptor_dim": int(self.embeddings.shape[1]),
            "created_at": datetime.now(UTC).isoformat(),
            "license": "synthetic renders generated by this repository",
            "notes": (
                "Classical colour/gradient/spatial descriptor + k-NN. Trained on "
                "procedurally generated synthetic renders. Intended as a CPU "
                "baseline and pipeline demonstrator, not a production recogniser."
            ),
            **self.metadata,
        }
        (directory / "metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
        return directory

    @classmethod
    def load(cls, directory: Path) -> VisionBaseline:
        npz_path = directory / "embeddings.npz"
        meta_path = directory / "metadata.json"
        if not npz_path.exists() or not meta_path.exists():
            raise ArtifactNotFound(
                f"Vision artifact missing at {directory}. Run `make train` (or "
                "`python -m training.vision.train`) before calling the vision API."
            )
        data = np.load(npz_path, allow_pickle=False)
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        return cls(
            embeddings=data["embeddings"].astype(np.float32),
            part_numbers=[str(x) for x in data["part_numbers"]],
            labels=[str(x) for x in data["labels"]],
            categories=[str(x) for x in data["categories"]],
            image_size=int(meta.get("image_size", 64)),
            name=meta.get("name", "vision-knn-baseline"),
            version=meta.get("version", "0.1.0"),
            runtime=meta.get("runtime", "python-numpy"),
            precision=meta.get("precision", "fp32"),
            metadata=meta,
        )
